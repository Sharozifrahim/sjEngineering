export function initChatbot(){
  const launcher = document.getElementById("chat-launcher");
  const panel = document.getElementById("chat-panel");
  const closeBtn = document.getElementById("chat-close");
  const body = document.getElementById("chat-body");
  const form = document.getElementById("chat-form");
  const input = document.getElementById("chat-input");
  const chipsWrap = document.getElementById("chat-chips");
  const keyLink = document.getElementById("chat-key-link");

  if(!launcher || !panel) return;

  let history = load();
  let awaitingKey = false;

  function load(){
    try{ return JSON.parse(sessionStorage.getItem(STORE_KEY)) || []; }
    catch{ return []; }
  }
  function save(){ sessionStorage.setItem(STORE_KEY, JSON.stringify(history)); }

  function addMessage(role, html){
    const el = document.createElement("div");
    el.className = `msg ${role === "user" ? "user" : "bot"}`;
    el.innerHTML = html;
    body.appendChild(el);
    body.scrollTop = body.scrollHeight;
    return el;
  }

  function renderHistory(){
    body.innerHTML = "";
    if(history.length === 0){
      addMessage("bot", `👋 Hi, I'm the ${KB.company.name} assistant. Ask me about our services, tools, or how to get a quote.`);
      return;
    }
    history.forEach(m => addMessage(m.role === "user" ? "user" : "bot", linkify(m.content)));
  }

  function linkify(text){
    return text.replace(/\n/g, "<br>");
  }

  const CHIPS = ["Fabrication & Erection", "Boiler Maintenance", "Solar Power Solutions", "Get a quote"];
  chipsWrap.innerHTML = CHIPS.map(c => `<button class="chip" type="button">${c}</button>`).join("");
  chipsWrap.querySelectorAll(".chip").forEach(chip=>{
    chip.addEventListener("click", ()=>{
      input.value = chip.textContent === "Get a quote" ? "How do I get a quote?" : `Tell me about ${chip.textContent}`;
      form.requestSubmit();
    });
  });

  launcher.addEventListener("click", ()=>{
    panel.classList.add("open");
    if(history.length === 0) renderHistory();
    input.focus();
  });
  closeBtn.addEventListener("click", ()=> panel.classList.remove("open"));

  keyLink.addEventListener("click", (e)=>{
    e.preventDefault();
    const current = localStorage.getItem(API_KEY_STORE) || "";
    const key = prompt("Paste a free Groq API key to upgrade to full AI answers (get one at console.groq.com). Leave blank to keep using the built-in knowledge base.", current);
    if(key !== null){
      if(key.trim()) localStorage.setItem(API_KEY_STORE, key.trim());
      else localStorage.removeItem(API_KEY_STORE);
      keyLink.textContent = key.trim() ? "AI mode: on ⚡ (click to change)" : "Enable full AI mode ⚡ (optional)";
    }
  });
  const savedKey = localStorage.getItem(API_KEY_STORE);
  keyLink.textContent = savedKey ? "AI mode: on ⚡ (click to change)" : "Enable full AI mode ⚡ (optional)";

  form.addEventListener("submit", async (e)=>{
    e.preventDefault();
    const text = input.value.trim();
    if(!text) return;
    input.value = "";

    history.push({ role:"user", content:text });
    addMessage("user", linkify(text));
    save();

    const typingEl = addMessage("bot", `<span class="typing"><span></span><span></span><span></span></span>`);

    let replyHTML;
    // const apiKey = localStorage.getItem(API_KEY_STORE);
    const apiKey=process.env.GROK_API_KEY || import.meta.env.GROK_API_KEY
    if(apiKey){
      try{
        const reply = await llmAnswer(history, apiKey);
        replyHTML = linkify(reply || fallbackAnswer());
      }catch(err){
        replyHTML = localAnswer(text) || `⚠️ Couldn't reach the AI service (${err.message}). ` + fallbackAnswer();
      }
    }else{
      replyHTML = localAnswer(text) || fallbackAnswer();
    }

    typingEl.innerHTML = replyHTML;
    history.push({ role:"assistant", content: replyHTML });
    save();
    body.scrollTop = body.scrollHeight;
  });

  renderHistory();
}
