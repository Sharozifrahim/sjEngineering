// ---------------------------------------------------------------
// 2. Local answer engine (keyword scoring — no dependencies)
// ---------------------------------------------------------------
function localAnswer(query){
  const q = query.toLowerCase();

  const contactWords = ["contact","phone","number","call","email","address","location","whatsapp","reach"];
  if(contactWords.some(w=>q.includes(w))){
    return `You can reach ${KB.company.name} at ${KB.company.phones.join(" or ")}, or by email at ${KB.company.email}.<br>Workshop: ${KB.company.address}<br><a href="${waLink('Hi SJ Engineering, I would like to get in touch.')}" target="_blank" rel="noopener">Message us on WhatsApp →</a>`;
  }

  if(/vision/.test(q)) return KB.company.vision;
  if(/mission/.test(q)) return KB.company.mission;
  if(/ceo|director|leadership|who runs|founder/.test(q)) return `${KB.company.name} is led by ${KB.company.leadership}`;
  if(/about|who are you|what is sj|company/.test(q) && !/service|product/.test(q)) return KB.company.about;
  if(/tool|equipment|machine/.test(q)) return `Our workshop runs a full fleet of fabrication and site equipment, including ${KB.tools.slice(0,8).join(", ")}, and more — ${KB.tools.length} machine types in total.`;
  if(/why (choose|you|sj)|advantage|different/.test(q)) return KB.why.map(w=>`• ${w}`).join("<br>");

  // service matching — score each service by keyword overlap
  let best = null, bestScore = 0;
  KB.services.forEach(s=>{
    const hay = (s.name + " " + s.body).toLowerCase();
    let score = 0;
    q.split(/\W+/).filter(Boolean).forEach(word=>{
      if(word.length > 2 && hay.includes(word)) score++;
    });
    if(score > bestScore){ bestScore = score; best = s; }
  });
  if(best && bestScore > 0){
    return `<strong>${best.name}</strong><br>${best.body}<br><a href="${waLink('Hi, I would like a quote for ' + best.name + '.')}" target="_blank" rel="noopener">Ask for a quote on WhatsApp →</a>`;
  }

  if(/service|product|offer|what do you do/.test(q)){
    return `We work across eight core lines: ${KB.services.map(s=>s.name).join(", ")}. Ask me about any one of these for details.`;
  }

  return null; // signal: no confident local match
}

function fallbackAnswer(){
  return `I don't have a confident answer for that from our service data yet. Our team can help directly — <a href="${waLink('Hi SJ Engineering, I have a question:')}" target="_blank" rel="noopener">chat with us on WhatsApp →</a>`;
}

